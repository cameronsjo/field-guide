#!/usr/bin/env python3
"""Write the generated data files the site reads.

  data/workbooks.json   -> docs/assets/catalog.js   (library home, cheat sheets index)
  data/vocabulary.json  -> docs/recipe/data.js      (recipe builder cards)
  data/presets.json     ->   "                      (recipe builder starter recipes)

Run after adding or changing a workbook:  python3 scripts/build.py
Refresh data/vocabulary.json first with:   npm run vocab
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA, DOCS = ROOT / "data", ROOT / "docs"


def js_payload(name, value):
    body = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return f"// Generated by scripts/build.py. Edit the files in data/ instead.\nwindow.{name} = {body};\n"


REDIRECT = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Moved</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="{to}">
<script>location.replace("{to}" + location.hash)</script>
<meta http-equiv="refresh" content="0; url={to}">
</head><body><p>This page moved to <a href="{to}">{to}</a>.</p></body></html>
"""


def write_redirects(books):
    """Old flat links (motion.html, recipe.html) keep working after the move to folders."""
    old = {f"{b['slug']}.html": f"workbooks/{b['slug']}/" for b in books}
    old["recipe.html"] = "recipe/"
    for name, to in old.items():
        (DOCS / name).write_text(REDIRECT.format(to=to))


def main():
    catalog = json.loads((DATA / "workbooks.json").read_text())
    vocab = json.loads((DATA / "vocabulary.json").read_text())
    presets = json.loads((DATA / "presets.json").read_text())
    books = catalog["workbooks"]

    missing = [b["slug"] for b in books if not (DOCS / "workbooks" / b["slug"] / "index.html").exists()]
    if missing:
        raise SystemExit(f"No page in docs/workbooks/ for: {', '.join(missing)}")

    (DOCS / "assets" / "catalog.js").write_text(js_payload("CATALOG", catalog))

    wb, cards, key = [], [], {}
    for i, b in enumerate(books):
        wb.append({"title": b["title"], "group": b["group"], "slug": b["slug"]})
        for subject in vocab.get(b["slug"], []):
            for c in subject["cards"]:
                key[(b["slug"], subject["subject"], c["name"])] = len(cards)
                key.setdefault((b["slug"], c["name"]), len(cards))
                cards.append([i, subject["subject"], c["name"], c["aka"], c["desc"], c["phrase"]])

    resolved = []
    for p in presets:
        try:
            ids = [key[tuple(c)] for c in p["cards"]]
        except KeyError as e:
            raise SystemExit(f"Preset '{p['name']}' names a card that doesn't exist: {e}")
        resolved.append({**p, "cards": ids})

    write_redirects(books)
    (DOCS / "recipe" / "data.js").write_text(js_payload("RECIPE_DATA", {"WB": wb, "CARDS": cards, "PRESETS": resolved}))
    print(f"{len(books)} workbooks, {len(cards):,} cards, {len(resolved)} presets")


if __name__ == "__main__":
    main()
